package dungeon;

/**
 * Race interface : Permet l'implémentation de nouvelle race.
 */
public interface Race {
    /**
     * doRace methode : permet d'avoir les attribues de la race.
     */
    void doRace();

    /**
     * afficheStats methode : permet d'afficher les stats du personnage.
     */
    void afficheStats();
}